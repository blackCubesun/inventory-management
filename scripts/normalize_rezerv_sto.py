import pandas as pd
import os

PROCESSED = r'C:\Users\92585\Desktop\Sklad_System\data\processed'

# Загружаем Резервы
df = pd.read_excel(os.path.join(PROCESSED, 'Резервы_плоский.xlsx'))
df['Код'] = df['Код'].astype(str).str.zfill(8)

# Словарь замен: старые → новые
replace_sto = {
    'Подразделение 11Э (Красная Пахра)': 'Подразделение Красная Пахра',
    'Подразделение 17А (Коньково)': 'Подразделение Коньково',
    'Подразделение 2Э (Фили)': 'Подразделение Фили',
    'Подразделение 6А (Нагорная)': 'Подразделение Нагорная',
    'Подразделение 7Э (Верхние Лихоборы)': 'Подразделение Лихоборы',
    'Подразделение 8А (Новокосино)': 'Подразделение Новокосино',
    'Подразделение 8Э (Новокосино Электробусы)': 'Подразделение Новокосино',
}

# Проверяем, что замена сработает
print('СТО до замены:')
print(sorted(df['СТО'].unique()))

df['СТО'] = df['СТО'].replace(replace_sto)

print('\nСТО после замены:')
print(sorted(df['СТО'].unique()))

# Агрегируем: если после замены есть дубли (СТО+Код), суммируем
df_agg = df.groupby(['Код', 'СТО']).agg({
    'Резерв': 'sum',
    'SKN': 'first',
    'Артикул': 'first',
    'Наименование': 'first'
}).reset_index()

print(f'\nСтрок до: {len(df)}')
print(f'Строк после агрегации: {len(df_agg)}')

df_agg.to_excel(os.path.join(PROCESSED, 'Резервы_плоский_испр.xlsx'), index=False)
print('\nСохранено: Резервы_плоский_испр.xlsx')